namespace {

/// The blank glyph: anything the font does not know draws as this.
const uint8_t kSpace[7] = {0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};

/// Row-major 5x7 glyphs, bit 4 leftmost. Space and punctuation fill out the
/// charset the HUD actually prints; anything else renders as a space.
const uint8_t* find_glyph(char c)
{
    static const uint8_t kDigits[10][7] = {
        {0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E},  // 0
        {0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E},  // 1
        {0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F},  // 2
        {0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E},  // 3
        {0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02},  // 4
        {0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E},  // 5
        {0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E},  // 6
        {0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08},  // 7
        {0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E},  // 8
        {0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C},  // 9
    };
    static const uint8_t kLetters[26][7] = {
        {0x04, 0x0A, 0x11, 0x11, 0x1F, 0x11, 0x11},  // A
        {0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E},  // B
        {0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E},  // C
        {0x1C, 0x12, 0x11, 0x11, 0x11, 0x12, 0x1C},  // D
        {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F},  // E
        {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10},  // F
        {0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F},  // G
        {0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11},  // H
        {0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E},  // I
        {0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C},  // J
        {0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11},  // K
        {0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F},  // L
        {0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11},  // M
        {0x11, 0x19, 0x15, 0x13, 0x11, 0x11, 0x11},  // N
        {0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E},  // O
        {0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10},  // P
        {0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D},  // Q
        {0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11},  // R
        {0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E},  // S
        {0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04},  // T
        {0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E},  // U
        {0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04},  // V
        {0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0A},  // W
        {0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11},  // X
        {0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04},  // Y
        {0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F},  // Z
    };
    static const uint8_t kPlus[7] = {0x00, 0x04, 0x04, 0x1F, 0x04, 0x04, 0x00};
    static const uint8_t kMinus[7] = {0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00};
    static const uint8_t kColon[7] = {0x00, 0x04, 0x04, 0x00, 0x04, 0x04, 0x00};
    static const uint8_t kDot[7] = {0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C};
    static const uint8_t kSlash[7] = {0x01, 0x02, 0x02, 0x04, 0x08, 0x08, 0x10};
    static const uint8_t kBang[7] = {0x04, 0x04, 0x04, 0x04, 0x04, 0x00, 0x04};
    static const uint8_t kGreater[7] = {0x10, 0x08, 0x04, 0x02, 0x04, 0x08, 0x10};
    static const uint8_t kPercent[7] = {0x19, 0x1A, 0x02, 0x04, 0x08, 0x0B, 0x13};
    static const uint8_t kEquals[7] = {0x00, 0x00, 0x1F, 0x00, 0x1F, 0x00, 0x00};
    static const uint8_t kParenOpen[7] = {0x02, 0x04, 0x08, 0x08, 0x08, 0x04, 0x02};
    static const uint8_t kParenClose[7] = {0x08, 0x04, 0x02, 0x02, 0x02, 0x04, 0x08};

    if (c >= '0' && c <= '9') return kDigits[c - '0'];
    if (c >= 'A' && c <= 'Z') return kLetters[c - 'A'];
    if (c >= 'a' && c <= 'z') return kLetters[c - 'a'];
    switch (c)
    {
        case '+': return kPlus;
        case '-': return kMinus;
        case ':': return kColon;
        case '.': return kDot;
        case '/': return kSlash;
        case '!': return kBang;
        case '>': return kGreater;
        case '%': return kPercent;
        case '=': return kEquals;
        case '(': return kParenOpen;
        case ')': return kParenClose;
    }
    return kSpace;
}

}  // namespace

int text_pixel_width(const std::string& text)
{
    if (text.empty()) return 0;
    return static_cast<int>(text.size()) * kGlyphAdvance - 1;
}

int text_lit_pixels(const std::string& text)
{
    int lit = 0;
    for (const char c : text)
    {
        const uint8_t* glyph = find_glyph(c);
        for (int row = 0; row < kGlyphHeight; ++row)
        {
            uint8_t bits = glyph[row];
            while (bits)
            {
                bits &= static_cast<uint8_t>(bits - 1);
                ++lit;
            }
        }
    }
    return lit;
}

bool font_has_glyph(char c)
{
    return find_glyph(c) != kSpace;
}

void append_text(PrimitiveSink& sink, const std::string& text, Vec2 top_left, float pixel)
{
    if (pixel <= 0.0f) return;

    float cursor = top_left.x;
    for (const char c : text)
    {
        const uint8_t* glyph = find_glyph(c);
        for (int row = 0; row < kGlyphHeight; ++row)
        {
            const uint8_t bits = glyph[row];
            for (int col = 0; col < kGlyphWidth; ++col)
            {
                if ((bits & (1 << (kGlyphWidth - 1 - col))) == 0) continue;
                // Each lit pixel is a square whose centre is half a pixel in
                // from the pixel's top-left corner.
                const float cx = cursor + (static_cast<float>(col) + 0.5f) * pixel;
                const float cy = top_left.y - (static_cast<float>(row) + 0.5f) * pixel;
                sink.quad(cx, cy, pixel * 0.5f, pixel * 0.5f, kZHudText);
            }
        }
        cursor += static_cast<float>(kGlyphAdvance) * pixel;
    }
}

float fit_text_pixel(const std::string& text, float max_width, float /*top_left_x*/, float default_pixel)
{
    // Shrink to fit, never enlarge. The size passed in is the one the caller's
    // layout was designed around — a card title, a tray label — so a name that
    // already fits keeps it. Growing to fill `max_width` instead would render a
    // three-letter weapon several times the height of the text beside it, and a
    // floor above the fitting size would let a long name overflow the box it is
    // being fitted into.
    const int width_px = text_pixel_width(text);
    if (width_px <= 0) return default_pixel;
    const float fit = max_width / static_cast<float>(width_px);
    return fit < default_pixel ? fit : default_pixel;
}

